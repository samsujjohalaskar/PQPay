
import hashlib
import hmac
import secrets
import time


# Experimental parameters.
# These are demonstration parameters, NOT production security parameters.
N = 4
Q = 97
SHORT_BOUND = 2


def generate_symmetric_matrix(n=N, q=Q):
    """Generate a symmetric n x n matrix modulo q."""
    matrix = [
        [secrets.randbelow(q) for _ in range(n)]
        for _ in range(n)
    ]

    return [
        [
            (matrix[i][j] + matrix[j][i]) % q
            for j in range(n)
        ]
        for i in range(n)
    ]


def generate_short_vector(n=N, bound=SHORT_BOUND):
    """Generate a small integer vector for the experiment."""
    return [
        secrets.randbelow(2 * bound + 1) - bound
        for _ in range(n)
    ]


def matrix_vector_multiply(matrix, vector, q=Q):
    """Compute A*x modulo q."""
    return [
        sum(matrix[i][j] * vector[j] for j in range(len(vector))) % q
        for i in range(len(matrix))
    ]


def dot_product_mod(a, b, q=Q):
    """Compute a^T*b modulo q."""
    return sum(x * y for x, y in zip(a, b)) % q


def derive_demo_key(session_key):
    """
    Derive a fixed-length key for the experimental handshake.

    WARNING: Q=97 gives a tiny key space. This is for simulation only,
    not secure encryption or production authentication.
    """
    return hashlib.sha256(
        f"PQPay-experimental-session-{session_key}".encode()
    ).digest()


def run_protocol():
    """
    Run an experimental matrix-based session-key agreement
    and challenge-response handshake.

    Both participants are simulated inside this backend function.
    This is not yet a client-to-server cryptographic handshake.
    """
    start = time.perf_counter()

    # 1. Public matrix generation
    A = generate_symmetric_matrix()

    # 2. User and server private vectors
    alpha = generate_short_vector()
    beta = generate_short_vector()

    # 3. Public vectors
    user_public = matrix_vector_multiply(A, alpha)
    server_public = matrix_vector_multiply(A, beta)

    # 4. Both sides independently compute the session key
    user_key = dot_product_mod(alpha, server_public)
    server_key = dot_product_mod(beta, user_public)

    if user_key != server_key:
        return {
            "authenticated": False,
            "reason": "Session key agreement failed",
            "security_time_ms": (time.perf_counter() - start) * 1000,
        }

    # 5. Fresh challenge generated by the server
    nonce = secrets.token_bytes(32)

    # 6. Server creates a challenge response
    session_key = derive_demo_key(server_key)
    server_proof = hmac.new(
        session_key,
        nonce,
        hashlib.sha256,
    ).digest()

    # 7. User-side simulation verifies the challenge response
    expected_proof = hmac.new(
        derive_demo_key(user_key),
        nonce,
        hashlib.sha256,
    ).digest()

    authenticated = hmac.compare_digest(
        server_proof,
        expected_proof,
    )

    elapsed_ms = (time.perf_counter() - start) * 1000

    return {
        "authenticated": authenticated,
        "reason": (
            "Experimental handshake successful"
            if authenticated
            else "Challenge verification failed"
        ),
        "security_time_ms": elapsed_ms,
        "session_keys_match": user_key == server_key,
        "challenge_verified": authenticated,
    }
